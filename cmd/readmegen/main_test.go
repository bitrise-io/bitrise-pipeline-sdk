// ---- collectBuilders -------------------------------------------------------

func TestCollectBuilders_FiltersDeprecatedAndSorts(t *testing.T) {
	dir := t.TempDir()

	writeBuilderFile(t, dir, "gen_script.go", "script", "1.0.0", "Script", false)
	writeBuilderFile(t, dir, "gen_git_clone.go", "git-clone", "8.0.0", "GitClone", false)
	writeBuilderFile(t, dir, "gen_old_step.go", "old-step", "1.0.0", "OldStep", true)
	writeBuilderFile(t, dir, "gen_android_build.go", "android-build", "1.0.0", "AndroidBuild", false)

	entries, err := collectBuilders(dir)
	require.NoError(t, err)

	// Should have 3 entries (deprecated old-step excluded), sorted by step ID.
	require.Len(t, entries, 3)
	assert.Equal(t, "android-build", entries[0].stepID)
	assert.Equal(t, "AndroidBuild", entries[0].funcName)
	assert.Equal(t, "git-clone", entries[1].stepID)
	assert.Equal(t, "script", entries[2].stepID)
}

