// ---- replaceMarkers --------------------------------------------------------

func TestReplaceMarkers_Basic(t *testing.T) {
	src := "before\n<!-- step-table-start -->\nold content\n<!-- step-table-end -->\nafter\n"
	replacement := []byte("new line 1\nnew line 2\n")

	out, err := replaceMarkers([]byte(src), markerStart, markerEnd, replacement)
	require.NoError(t, err)

	result := string(out)
	assert.Contains(t, result, "before")
	assert.Contains(t, result, markerStart)
	assert.Contains(t, result, "new line 1")
	assert.Contains(t, result, "new line 2")
	assert.Contains(t, result, markerEnd)
	assert.Contains(t, result, "after")
	assert.NotContains(t, result, "old content")
}

func TestReplaceMarkers_MissingStartMarker(t *testing.T) {
	src := "no markers here\n<!-- step-table-end -->\n"
	_, err := replaceMarkers([]byte(src), markerStart, markerEnd, []byte("x"))
	require.Error(t, err)
	assert.Contains(t, err.Error(), markerStart)
}

func TestReplaceMarkers_MissingEndMarker(t *testing.T) {
	src := "<!-- step-table-start -->\nno end\n"
	_, err := replaceMarkers([]byte(src), markerStart, markerEnd, []byte("x"))
	require.Error(t, err)
	assert.Contains(t, err.Error(), markerEnd)
}

func TestReplaceMarkers_EndBeforeStart(t *testing.T) {
	src := "<!-- step-table-end -->\n<!-- step-table-start -->\n"
	_, err := replaceMarkers([]byte(src), markerStart, markerEnd, []byte("x"))
	require.Error(t, err)
}

func TestReplaceMarkers_Idempotent(t *testing.T) {
	// Running the replacement twice with the same content should yield the same result.
	src := "header\n<!-- step-table-start -->\nold\n<!-- step-table-end -->\nfooter\n"
	replacement := []byte("new\n")

	first, err := replaceMarkers([]byte(src), markerStart, markerEnd, replacement)
	require.NoError(t, err)
	second, err := replaceMarkers(first, markerStart, markerEnd, replacement)
	require.NoError(t, err)
	assert.Equal(t, string(first), string(second))
}

// ---- updateReadme ----------------------------------------------------------

func TestUpdateReadme(t *testing.T) {
	readmePath := filepath.Join(t.TempDir(), "README.md")
	content := "# Title\n\n<!-- step-table-start -->\nstale content\n<!-- step-table-end -->\n\nfooter\n"
	require.NoError(t, os.WriteFile(readmePath, []byte(content), 0644))

	entries := []builderEntry{
		{stepID: "git-clone", funcName: "GitClone"},
	}
	require.NoError(t, updateReadme(readmePath, entries, nil))

	updated, err := os.ReadFile(readmePath)
	require.NoError(t, err)
	result := string(updated)

	assert.Contains(t, result, "# Title")
	assert.Contains(t, result, "footer")
	assert.Contains(t, result, "| `step.GitClone()` | `git-clone` |")
	assert.NotContains(t, result, "stale content")
}

func TestUpdateReadme_WithVersionsSection(t *testing.T) {
	readmePath := filepath.Join(t.TempDir(), "README.md")
	content := "# Title\n" +
		"<!-- step-table-start -->\nold\n<!-- step-table-end -->\n" +
		"### Versioned\n" +
		"<!-- step-versions-start -->\nold versions\n<!-- step-versions-end -->\n" +
		"footer\n"
	require.NoError(t, os.WriteFile(readmePath, []byte(content), 0644))

	entries := []builderEntry{{stepID: "git-clone", funcName: "GitClone"}}
	vEntries := []versionedBuilderEntry{
		{stepID: "git-clone", funcName: "GitCloneV7", major: 7},
		{stepID: "git-clone", funcName: "GitCloneV8", major: 8},
	}
	require.NoError(t, updateReadme(readmePath, entries, vEntries))

	updated, _ := os.ReadFile(readmePath)
	result := string(updated)

	assert.Contains(t, result, "| `step.GitClone()` |")
	assert.Contains(t, result, "| `step.GitCloneV7()` | `git-clone` | v7.x |")
	assert.Contains(t, result, "| `step.GitCloneV8()` | `git-clone` | v8.x |")
	assert.NotContains(t, result, "old versions")
}

