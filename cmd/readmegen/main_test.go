// ---- collectBuilders -------------------------------------------------------

func TestCollectBuilders_FiltersDeprecatedAndSorts(t *testing.T) {
	dir := t.TempDir()

	writeBuilderFile(t, dir, "gen_script.go", "script", "1.0.0", "Script", false)
	writeBuilderFile(t, dir, "gen_git_clone.go", "git-clone", "8.0.0", "GitClone", false)
	writeBuilderFile(t, dir, "gen_old_step.go", "old-step", "1.0.0", "OldStep", true)
	writeBuilderFile(t, dir, "gen_android_build.go", "android-build", "1.0.0", "AndroidBuild", false)

	entries, err := collectBuilders(dir)
	require.NoError(t, err)

	// Should have 3 entries (deprecated old-step excluded), sorted by step ID.
	require.Len(t, entries, 3)
	assert.Equal(t, "android-build", entries[0].stepID)
	assert.Equal(t, "AndroidBuild", entries[0].funcName)
	assert.Equal(t, "git-clone", entries[1].stepID)
	assert.Equal(t, "script", entries[2].stepID)
}

func TestCollectBuilders_SkipsVersionedFiles(t *testing.T) {
	dir := t.TempDir()

	// Single-major step: normal file.
	writeBuilderFile(t, dir, "gen_script.go", "script", "1.0.0", "Script", false)

	// Multi-major step: per-major versioned files are skipped, alias is included.
	writeBuilderFile(t, dir, "gen_xcode_test_v5.go", "xcode-test", "5.4.0", "XcodeTestV5", false)
	writeBuilderFile(t, dir, "gen_xcode_test_v6.go", "xcode-test", "6.2.0", "XcodeTestV6", false)
	writeAliasBuilderFile(t, dir, "gen_xcode_test_alias.go", "xcode-test", "6.2.0", "XcodeTest", "XcodeTestV6")

	entries, err := collectBuilders(dir)
	require.NoError(t, err)

	// Only 2 entries: script (single-major) and xcode-test (via alias).
	require.Len(t, entries, 2)
	assert.Equal(t, "script", entries[0].stepID)
	assert.Equal(t, "xcode-test", entries[1].stepID)
	assert.Equal(t, "XcodeTest", entries[1].funcName)
}

