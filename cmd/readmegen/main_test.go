// ---- parseStepID -----------------------------------------------------------

func TestParseStepID(t *testing.T) {
	tests := []struct {
		line    string
		want    string
		wantErr bool
	}{
		{"// Step: git-clone (8.2.1)", "git-clone", false},
		{"// Step: activate-ssh-key (4.1.1)", "activate-ssh-key", false},
		{"// Step: script (1.0.0)", "script", false},
		{"// Step: android-unit-test (1.2.3)", "android-unit-test", false},
		{"// Step: no-parens", "", true},
		{"", "", true},
	}
	for _, tt := range tests {
		t.Run(tt.line, func(t *testing.T) {
			got, err := parseStepID(tt.line)
			if tt.wantErr {
				require.Error(t, err)
			} else {
				require.NoError(t, err)
				assert.Equal(t, tt.want, got)
			}
		})
	}
}

// ---- parseConstructorName --------------------------------------------------

func TestParseConstructorName(t *testing.T) {
	tests := []struct {
		line string
		want string
		ok   bool
	}{
		{"func GitClone() *GitCloneBuilder {", "GitClone", true},
		{"func Script() *ScriptBuilder {", "Script", true},
		{"func AndroidUnitTest() *AndroidUnitTestBuilder {", "AndroidUnitTest", true},
		{"func (b *GitCloneBuilder) WithBranch(value string) *GitCloneBuilder {", "", false},
		{"type GitCloneBuilder struct{ *Builder }", "", false},
	}
	for _, tt := range tests {
		t.Run(tt.line, func(t *testing.T) {
			got, ok := parseConstructorName(tt.line)
			assert.Equal(t, tt.ok, ok)
			assert.Equal(t, tt.want, got)
		})
	}
}

// ---- parseBuilderFile ------------------------------------------------------

func TestParseBuilderFile_Normal(t *testing.T) {
	f := writeTempBuilderFile(t, `// Code generated by cmd/stepgen. DO NOT EDIT.
// Step: git-clone (8.2.1)

package step

// GitCloneBuilder builds a git-clone step with typed input methods.
type GitCloneBuilder struct{ *Builder }

// GitClone creates a git-clone step builder (v8).
func GitClone() *GitCloneBuilder {
	return &GitCloneBuilder{Builder: From("git-clone", "8")}
}
`)
	entry, deprecated, err := parseBuilderFile(f)
	require.NoError(t, err)
	assert.False(t, deprecated)
	assert.Equal(t, "git-clone", entry.stepID)
	assert.Equal(t, "GitClone", entry.funcName)
}

func TestParseBuilderFile_Deprecated(t *testing.T) {
	f := writeTempBuilderFile(t, `// Code generated by cmd/stepgen. DO NOT EDIT.
// Step: old-step (2.0.0)

package step

// OldStepBuilder builds a old-step step with typed input methods.
//
// Deprecated: Use new-step instead.
type OldStepBuilder struct{ *Builder }

// OldStep creates a old-step step builder (v2).
//
// Deprecated: Use new-step instead.
func OldStep() *OldStepBuilder {
	return &OldStepBuilder{Builder: From("old-step", "2")}
}
`)
	entry, deprecated, err := parseBuilderFile(f)
	require.NoError(t, err)
	assert.True(t, deprecated)
	assert.Equal(t, "old-step", entry.stepID)
	assert.Equal(t, "OldStep", entry.funcName)
}

