// ---- step-info.yml parsing -------------------------------------------------

type rawStepInfo struct {
	DeprecateNotes string `yaml:"deprecate_notes"`
	RemovalDate    string `yaml:"removal_date"`
}

// deprecationInfo holds deprecation metadata for a step.
type deprecationInfo struct {
	StepID      string
	Notes       string
	RemovalDate string
}

func parseStepInfo(data []byte) (*deprecationInfo, error) {
	if len(data) == 0 {
		return nil, nil
	}
	var raw rawStepInfo
	if err := yaml.Unmarshal(data, &raw); err != nil {
		return nil, fmt.Errorf("unmarshal step-info.yml: %w", err)
	}
	if raw.DeprecateNotes == "" {
		return nil, nil
	}
	return &deprecationInfo{
		// sanitizeComment collapses newlines so multi-paragraph notes are safe
		// to embed in a single-line // Deprecated: godoc comment.
		Notes:       sanitizeComment(raw.DeprecateNotes),
		RemovalDate: raw.RemovalDate,
	}, nil
}

// ---- step.yml parsing ------------------------------------------------------

type rawStepYML struct {
	Title  string                   `yaml:"title"`
	Inputs []map[string]interface{} `yaml:"inputs"`
}

func parseStepYML(stepID, version string, data []byte) (*stepDef, error) {
	var raw rawStepYML
	if err := yaml.Unmarshal(data, &raw); err != nil {
		return nil, fmt.Errorf("unmarshal YAML: %w", err)
	}

	def := &stepDef{
		StepID:       stepID,
		Version:      version,
		MajorVersion: majorVersion(version),
		Title:        raw.Title,
		TypeName:     toTypeName(stepID),
	}

	seen := map[string]bool{}
	for _, rawInput := range raw.Inputs {
		var key string
		var rawOpts interface{}
		for k, v := range rawInput {
			if k == "opts" {
				rawOpts = v
			} else {
				key = k
			}
		}
		if key == "" || !isValidIdentifier(key) {
			continue
		}

		in := inputDef{
			Key:        key,
			MethodName: toMethodName(key),
		}
		// Skip duplicate method names (can happen when a step.yml has the
		// same key listed multiple times with different default values).
		if seen[in.MethodName] {
			continue
		}
		seen[in.MethodName] = true

		if opts, ok := rawOpts.(map[interface{}]interface{}); ok {
			if title, _ := opts["title"].(string); title != "" {
				in.Comment = fmt.Sprintf("With%s sets %s.", in.MethodName, sanitizeComment(lcFirst(title)))
			}
		}
		if in.Comment == "" {
			in.Comment = fmt.Sprintf("With%s sets the %s input.", in.MethodName, key)
		}
		def.Inputs = append(def.Inputs, in)
	}
	return def, nil
}

// ---- helpers ---------------------------------------------------------------

// singleOutPath returns the output path for a step that has a single major
// version.  Steps ending in "-test" get a "_builder" suffix to prevent the Go
// build system from misidentifying the file as a test file (e.g. xcode-test →
// gen_xcode_test_builder.go).
func singleOutPath(outputDir, stepID string) string {
	base := "gen_" + normalizeID(stepID)
	if strings.HasSuffix(base, "_test") {
		base += "_builder"
	}
	return filepath.Join(outputDir, base+".go")
}

// versionedOutPath returns the output path for the per-major builder file.
// e.g. stepID="xcode-test", major=6 → "gen_xcode_test_v6.go".
// The "_v{N}" suffix avoids the "_test.go" build-exclusion problem.
func versionedOutPath(outputDir, stepID string, major int) string {
	return filepath.Join(outputDir, "gen_"+normalizeID(stepID)+"_v"+strconv.Itoa(major)+".go")
}

// aliasOutPath returns the output path for the alias file of a multi-major step.
// e.g. stepID="xcode-test" → "gen_xcode_test_alias.go".
func aliasOutPath(outputDir, stepID string) string {
	return filepath.Join(outputDir, "gen_"+normalizeID(stepID)+"_alias.go")
}

// majorVersionNums returns the sorted list of unique major version numbers
// present in the given version strings.
func majorVersionNums(versions []string) []int {
	seen := make(map[int]bool)
	for _, v := range versions {
		maj, _ := strconv.Atoi(majorVersion(v))
		seen[maj] = true
	}
	nums := make([]int, 0, len(seen))
	for n := range seen {
		nums = append(nums, n)
	}
	sort.Ints(nums)
	return nums
}

// latestOfMajor returns the latest version string within the given major
// version number from the provided version list.
func latestOfMajor(versions []string, major int) string {
	prefix := strconv.Itoa(major) + "."
	exact := strconv.Itoa(major)
	var filtered []string
	for _, v := range versions {
		if strings.HasPrefix(v, prefix) || v == exact {
			filtered = append(filtered, v)
		}
	}
	if len(filtered) == 0 {
		return ""
	}
	return latestVersion(filtered)
}

func latestVersion(versions []string) string {
	sort.Slice(versions, func(i, j int) bool {
		return cmpVer(versions[i], versions[j]) < 0
	})
	return versions[len(versions)-1]
}

func cmpVer(a, b string) int {
	pa, pb := splitVer(a), splitVer(b)
	for i := range pa {
		if pa[i] != pb[i] {
			if pa[i] < pb[i] {
				return -1
			}
			return 1
		}
	}
	return 0
}

func splitVer(v string) [3]int {
	parts := strings.SplitN(v, ".", 3)
	var r [3]int
	for i, p := range parts {
		if i >= 3 {
			break
		}
		r[i], _ = strconv.Atoi(p)
	}
	return r
}

func majorVersion(v string) string {
	if idx := strings.IndexByte(v, '.'); idx >= 0 {
		return v[:idx]
	}
	return v
}

func normalizeID(id string) string {
	return strings.ReplaceAll(id, "-", "_")
}

func toTypeName(id string) string {
	var b strings.Builder
	for _, part := range strings.Split(id, "-") {
		if len(part) > 0 {
			b.WriteRune(unicode.ToUpper(rune(part[0])))
			b.WriteString(part[1:])
		}
	}
	return b.String()
}

func toMethodName(key string) string {
	var b strings.Builder
	for _, part := range strings.Split(key, "_") {
		if len(part) > 0 {
			b.WriteRune(unicode.ToUpper(rune(part[0])))
			b.WriteString(part[1:])
		}
	}
	return b.String()
}

func isValidIdentifier(key string) bool {
	if key == "" {
		return false
	}
	for _, r := range key {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) && r != '_' {
			return false
		}
	}
	return !unicode.IsDigit(rune(key[0]))
}

func lcFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func sanitizeComment(s string) string {
	return strings.ReplaceAll(strings.TrimSpace(s), "\n", " ")
}

func fatalf(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, "stepgen: "+format+"\n", args...)
	os.Exit(1)
}
