package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const oldConstructor = `// Code generated by cmd/stepgen. DO NOT EDIT.
// Step: git-clone (8.2.1)

package step

// GitCloneBuilder builds a git-clone step with typed input methods.
type GitCloneBuilder struct{ *Builder }

// GitClone creates a git-clone step builder (v8).
func GitClone() *GitCloneBuilder {
	return &GitCloneBuilder{Builder: From("git-clone", "8")}
}

// WithBranch sets branch to checkout.
func (b *GitCloneBuilder) WithBranch(value string) *GitCloneBuilder {
	b.Builder.WithInput("branch", value)
	return b
}
`

const newConstructor = `func GitClone(version ...string) *GitCloneBuilder {
	v := "8"
	if len(version) > 0 && version[0] != "" {
		v = version[0]
	}
	return &GitCloneBuilder{Builder: From("git-clone", v)}
}`

func TestPatchFile_TransformsOldConstructor(t *testing.T) {
	path := writeTempFile(t, oldConstructor)

	changed, err := patchFile(path)
	require.NoError(t, err)
	assert.True(t, changed)

	result, _ := os.ReadFile(path)
	content := string(result)
	assert.Contains(t, content, "func GitClone(version ...string) *GitCloneBuilder {")
	assert.Contains(t, content, `v := "8"`)
	assert.Contains(t, content, `if len(version) > 0 && version[0] != "" {`)
	assert.Contains(t, content, `return &GitCloneBuilder{Builder: From("git-clone", v)}`)
	// Original input method should be preserved.
	assert.Contains(t, content, "func (b *GitCloneBuilder) WithBranch")
}

func TestPatchFile_AlreadyPatched(t *testing.T) {
	// A file that already has the variadic constructor should report no change.
	alreadyPatched := strings.Replace(oldConstructor,
		"func GitClone() *GitCloneBuilder {\n\treturn &GitCloneBuilder{Builder: From(\"git-clone\", \"8\")}\n}",
		newConstructor, 1)
	path := writeTempFile(t, alreadyPatched)
	original, _ := os.ReadFile(path)

	changed, err := patchFile(path)
	require.NoError(t, err)
	assert.False(t, changed)

	after, _ := os.ReadFile(path)
	assert.Equal(t, string(original), string(after))
}

func TestPatchFile_PreservesDeprecatedComment(t *testing.T) {
	src := `// Code generated by cmd/stepgen. DO NOT EDIT.
// Step: old-step (2.0.0)

package step

// OldStepBuilder builds a old-step step with typed input methods.
//
// Deprecated: Use new-step instead.
type OldStepBuilder struct{ *Builder }

// OldStep creates a old-step step builder (v2).
//
// Deprecated: Use new-step instead.
func OldStep() *OldStepBuilder {
	return &OldStepBuilder{Builder: From("old-step", "2")}
}
`
	path := writeTempFile(t, src)

	changed, err := patchFile(path)
	require.NoError(t, err)
	assert.True(t, changed)

	result, _ := os.ReadFile(path)
	content := string(result)
	assert.Contains(t, content, "// Deprecated: Use new-step instead.")
	assert.Contains(t, content, "func OldStep(version ...string) *OldStepBuilder {")
}

func TestPatchFile_MissingFile(t *testing.T) {
	_, err := patchFile("/nonexistent/gen_step.go")
	require.Error(t, err)
}

func TestConstructorRe_MatchesExpected(t *testing.T) {
	src := "func Script() *ScriptBuilder {\n\treturn &ScriptBuilder{Builder: From(\"script\", \"1\")}\n}"
	assert.True(t, constructorRe.MatchString(src))

	// Should not match variadic signature (already patched).
	patched := "func Script(version ...string) *ScriptBuilder {\n\tv := \"1\"\n}"
	assert.False(t, constructorRe.MatchString(patched))

	// Should not match input methods.
	method := "func (b *ScriptBuilder) WithContent(value string) *ScriptBuilder {\n\treturn b\n}"
	assert.False(t, constructorRe.MatchString(method))
}

// ---- helpers ---------------------------------------------------------------

func writeTempFile(t *testing.T, content string) string {
	t.Helper()
	f, err := os.CreateTemp(t.TempDir(), "gen_*.go")
	require.NoError(t, err)
	_, err = f.WriteString(content)
	require.NoError(t, err)
	require.NoError(t, f.Close())
	return f.Name()
}

func TestPatchFile_MultipleStepsInOneRun(t *testing.T) {
	dir := t.TempDir()

	steps := map[string]string{
		"gen_script.go":    `// Code generated by cmd/stepgen. DO NOT EDIT.` + "\n// Step: script (1.0.0)\n\npackage step\n\ntype ScriptBuilder struct{ *Builder }\n\nfunc Script() *ScriptBuilder {\n\treturn &ScriptBuilder{Builder: From(\"script\", \"1\")}\n}\n",
		"gen_git_clone.go": `// Code generated by cmd/stepgen. DO NOT EDIT.` + "\n// Step: git-clone (8.0.0)\n\npackage step\n\ntype GitCloneBuilder struct{ *Builder }\n\nfunc GitClone() *GitCloneBuilder {\n\treturn &GitCloneBuilder{Builder: From(\"git-clone\", \"8\")}\n}\n",
	}

	for name, content := range steps {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0644))
	}

	paths, _ := filepath.Glob(filepath.Join(dir, "gen_*.go"))
	updated := 0
	for _, p := range paths {
		changed, err := patchFile(p)
		require.NoError(t, err)
		if changed {
			updated++
		}
	}
	assert.Equal(t, 2, updated)

	for _, name := range []string{"gen_script.go", "gen_git_clone.go"} {
		data, _ := os.ReadFile(filepath.Join(dir, name))
		assert.Contains(t, string(data), "version ...string", name)
	}
}
